const DICTS = { en, fr, es, de, ar };

let current = 'en';
const listeners = new Set();

export function detectLang() {
  for (const nav of navigator.languages || [navigator.language || 'en']) {
    const code = String(nav).slice(0, 2).toLowerCase();
    if (DICTS[code]) return code;
  }
  return 'en';
}

export function setLang(code) {
  current = code === 'auto' ? detectLang() : (DICTS[code] ? code : 'en');
  const meta = LANGS.find(l => l.code === current);
  document.documentElement.lang = current;
  document.documentElement.dir = meta.dir;
  listeners.forEach(f => f(current));
  return current;
}
export const getLang = () => current;
export const getLangMeta = () => LANGS.find(l => l.code === current);
export const onLangChange = fn => { listeners.add(fn); return () => listeners.delete(fn); };

/** Translate. Falls back through the current dict → English → the key. */
export function t(key, vars) {
  let s = DICTS[current]?.[key] ?? en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
  return s;
}

/** Wrap a signed/technical run so bidi cannot reorder it: "+142 kcal"
    must not render as "142+ kcal" inside an Arabic paragraph. */
export const ltr = str => getLangMeta().dir === 'rtl' ? `\u2066${str}\u2069` : String(str);

/* ── Locale-aware formatting ──────────────────────────────────────── */
export const locale = () => getLangMeta().locale;
export const nf = (n, opts) => new Intl.NumberFormat(locale(), opts).format(n);
export const df = (date, opts) => new Intl.DateTimeFormat(locale(), opts).format(date);
export function weekdayShort(date) { return df(date, { weekday: 'short' }); }
export function dateMedium(date) { return df(date, { day: 'numeric', month: 'short' }); }
export function dateFull(date) { return df(date, { weekday: 'long', day: 'numeric', month: 'long' }); }
export function timeShort(date) { return df(date, { hour: '2-digit', minute: '2-digit' }); }
